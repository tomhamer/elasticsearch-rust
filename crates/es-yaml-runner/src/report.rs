//! Markdown / JSON reports.

use crate::TestResult;
use crate::exec::Outcome;
use serde_json::json;
use std::collections::BTreeMap;
use std::path::Path;

const NOTES_START: &str = "<!-- notes:start -->";
const NOTES_END: &str = "<!-- notes:end -->";

/// The work-stream area a YAML test category belongs to, used to group the report.
fn owner(category: &str, dir: &str) -> &'static str {
    let c = format!("{} {}", category.to_lowercase(), dir.to_lowercase());
    let has = |k: &str| c.contains(k);
    if has("reindex") || has("update_by_query") || has("delete_by_query") || has("tasks") {
        "reindex/tasks"
    } else if has("field_caps") {
        "field_caps"
    } else if has("async_search") {
        "async search"
    } else if has("data_stream") || has("rollover") {
        "data streams"
    } else if has("script") || has("painless") {
        "scripting"
    } else if has("nested") || has("geo") {
        "nested/geo"
    } else {
        ""
    }
}

fn md_escape(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ").replace('`', "'")
}

pub fn write_json(path: &Path, results: &[TestResult]) {
    let v: Vec<_> = results
        .iter()
        .map(|r| {
            let (status, msg, cat) = match &r.outcome {
                Outcome::Pass => ("pass", String::new(), String::new()),
                Outcome::Fail { msg, category } => ("fail", msg.clone(), category.clone()),
                Outcome::Skip(s) => ("skip", s.clone(), String::new()),
            };
            json!({"file": r.file, "dir": r.dir, "name": r.name, "status": status, "msg": msg, "category": cat})
        })
        .collect();
    let _ = std::fs::write(path, serde_json::to_vec_pretty(&v).unwrap_or_default());
}

#[derive(Default)]
struct Counts {
    pass: usize,
    fail: usize,
    skip: usize,
}

pub fn write_markdown(path: &Path, results: &[TestResult], version: &str, filters: &[String]) {
    let old_notes = std::fs::read_to_string(path).ok().and_then(|s| {
        let a = s.find(NOTES_START)?;
        let b = s.find(NOTES_END)?;
        Some(s[a..b + NOTES_END.len()].to_string())
    });
    let mut total = Counts::default();
    let mut per_dir: BTreeMap<&str, Counts> = BTreeMap::new();
    let mut causes: BTreeMap<&str, Vec<&TestResult>> = BTreeMap::new();
    let mut skips: BTreeMap<String, usize> = BTreeMap::new();
    for r in results {
        let d = per_dir.entry(r.dir.as_str()).or_default();
        match &r.outcome {
            Outcome::Pass => {
                total.pass += 1;
                d.pass += 1;
            }
            Outcome::Fail { category, .. } => {
                total.fail += 1;
                d.fail += 1;
                causes.entry(category.as_str()).or_default().push(r);
            }
            Outcome::Skip(why) => {
                total.skip += 1;
                d.skip += 1;
                let key = if why.starts_with("requires cluster feature `gte_v") { "requires newer version feature".to_string() } else { why.clone() };
                *skips.entry(key).or_default() += 1;
            }
        }
    }
    let ran = total.pass + total.fail;
    let pct = |p: usize, n: usize| if n == 0 { 0.0 } else { 100.0 * p as f64 / n as f64 };
    let mut s = String::new();
    s.push_str("# Elasticsearch YAML REST suite compatibility\n\n");
    s.push_str(&format!(
        "Generated by `cargo run -p es-yaml-runner -- --report` against Elasticsearch's own YAML REST tests \
         (`rest-api-spec` tests, tag `{version}`, fetched by `tests/es-yaml/fetch.sh`). Each test section runs against a \
         fresh in-process `elasticsearch-http` server with an empty temp data dir (stronger isolation than ES's `wipeCluster`).\n\n"
    ));
    if !filters.is_empty() {
        s.push_str(&format!("**Filtered run:** `{}`\n\n", filters.join(", ")));
    }
    s.push_str("Required missing gates count as failures by default. Skipped/excluded cases have not passed. This report does not establish full ES9 parity.\n\n");
    s.push_str("## Overall\n\n| tests | pass | fail | skip | pass rate (of run) | pass rate (of all) |\n|---:|---:|---:|---:|---:|---:|\n");
    s.push_str(&format!(
        "| {} | {} | {} | {} | {:.1}% | {:.1}% |\n\n",
        results.len(),
        total.pass,
        total.fail,
        total.skip,
        pct(total.pass, ran),
        pct(total.pass, results.len())
    ));
    s.push_str(
        "Runner semantics: server version is treated as the pinned 8.x tag; `gte_v*` cluster features are satisfied, other named \
         cluster features and `capabilities` are asked of the node (`_cluster/state` `nodes_features`, `GET _capabilities`), as \
         ES's runner does; runner features are exactly ES's `Features.SUPPORTED` (so `regex` / `skip_os` / `fips_140` tests are \
         skipped, as in ES) and `xpack` / `no_xpack` follow the cluster (`--no-xpack` for this suite); `warnings` / \
         `allowed_warnings` (and `_regex`) are checked; `node_selector` is ignored (single node).\n\n",
    );
    if let Some(n) = old_notes {
        s.push_str("## Notes\n\n");
        s.push_str(&n);
        s.push_str("\n\n");
    }

    s.push_str("## Per API directory (sorted by failures)\n\n| directory | pass | fail | skip | pass rate (of run) | owner of failures |\n|---|---:|---:|---:|---:|---|\n");
    let mut dirs: Vec<_> = per_dir.iter().collect();
    dirs.sort_by(|a, b| b.1.fail.cmp(&a.1.fail).then(a.1.pass.cmp(&b.1.pass).reverse()).then(a.0.cmp(b.0)));
    for (d, c) in dirs {
        let o = owner("", d);
        s.push_str(&format!("| `{d}` | {} | {} | {} | {:.0}% | {o} |\n", c.pass, c.fail, c.skip, pct(c.pass, c.pass + c.fail)));
    }

    s.push_str("\n## Top 50 failure causes\n\nGrouped by the first failing step (normalised: numbers → `N`, bracketed values → `[*]`). \"owner\" marks areas other work streams are building.\n\n");
    s.push_str("| # | count | cause | owner | examples |\n|---:|---:|---|---|---|\n");
    let mut cs: Vec<_> = causes.iter().collect();
    cs.sort_by(|a, b| b.1.len().cmp(&a.1.len()).then(a.0.cmp(b.0)));
    for (i, (cat, rs)) in cs.iter().take(50).enumerate() {
        let ex: Vec<String> = rs.iter().take(3).map(|r| format!("`{}` :: {}", md_escape(&r.file), md_escape(&r.name))).collect();
        let first_msg = match &rs[0].outcome {
            Outcome::Fail { msg, .. } => msg.chars().take(220).collect::<String>(),
            _ => String::new(),
        };
        s.push_str(&format!(
            "| {} | {} | `{}` <br>e.g. {} | {} | {} |\n",
            i + 1,
            rs.len(),
            md_escape(cat),
            md_escape(&first_msg),
            owner(cat, &rs[0].dir),
            ex.join("<br>")
        ));
    }

    s.push_str("\n## Skip reasons\n\n| reason | tests |\n|---|---:|\n");
    let mut sk: Vec<_> = skips.into_iter().collect();
    sk.sort_by(|a, b| b.1.cmp(&a.1));
    for (why, n) in sk.iter().take(40) {
        s.push_str(&format!("| {} | {n} |\n", md_escape(why)));
    }
    let _ = std::fs::write(path, s);
}
