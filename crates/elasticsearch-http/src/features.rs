/// `Some(true/false)` when the route is known, `None` when no such route exists
/// (the capabilities API then answers `"supported": null`).
pub fn capability_supported(method: &str, path: &str, params: &[&str], caps: &[&str]) -> Option<Value> {
    let method = method.to_ascii_uppercase();
    // Route templates match whatever their placeholders are named (`{index}` = `{target}`).
    let same = |a: &str, b: &str| {
        let (a, b): (Vec<&str>, Vec<&str>) = (a.split('/').collect(), b.split('/').collect());
        a.len() == b.len() && a.iter().zip(&b).all(|(x, y)| x == y || (x.starts_with('{') && y.starts_with('{')))
    };
    // A concrete path resolves like ES's `PathTrie`: placeholders match any
    // segment, literal segments win over placeholders.
    let concrete = |route: &str| -> Option<usize> {
        let (a, b): (Vec<&str>, Vec<&str>) = (route.split('/').collect(), path.split('/').collect());
        if a.len() != b.len() {
            return None;
        }
        let mut literal = 0;
        for (x, y) in a.iter().zip(&b) {
            if x == y {
                literal += 1;
            } else if !(x.starts_with('{') && !y.is_empty()) {
                return None;
            }
        }
        Some(literal)
    };
    let route = ROUTES
        .iter()
        .find(|r| r.path == path && r.methods.contains(&method.as_str()))
        .or_else(|| ROUTES.iter().find(|r| same(r.path, path) && r.methods.contains(&method.as_str())))
        .or_else(|| ROUTES.iter().filter(|r| r.methods.contains(&method.as_str())).filter_map(|r| concrete(r.path).map(|n| (n, r))).max_by_key(|(n, _)| *n).map(|(_, r)| r))?;
    let esql = route.caps.as_ptr() == ESQL_CAPS.as_ptr();
    let ok = params.iter().all(|p| route.params.contains(p) || ALWAYS_SUPPORTED.contains(p)) && caps.iter().all(|c| route.caps.contains(c) || (esql && ESQL_FN_CAPS.contains(c)));
    Some(json!(ok))
}

