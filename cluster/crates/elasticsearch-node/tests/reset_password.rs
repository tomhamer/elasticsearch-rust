//! `elasticsearch-reset-password` against an in-process secured node: the
//! temporary file-realm superuser is picked up by the node's file watcher,
//! the password is reset through the REST API, and the temporary user is
//! removed again.
#[path = "common/evidence.rs"]
mod evidence;
#[path = "common/ports.rs"]
mod ports;

use elasticsearch_node::config::{NodeConfig, Settings};
use elasticsearch_node::reset_password::{parse_args, run, Terminal};
use serde_json::json;
use std::collections::{BTreeMap, VecDeque};
use std::time::Duration;

#[derive(Default)]
struct Script {
    out: String,
    err: String,
    lines: VecDeque<String>,
    secrets: VecDeque<String>,
}

impl Terminal for Script {
    fn print(&mut self, text: &str) {
        self.out.push_str(text);
    }
    fn eprintln(&mut self, text: &str) {
        self.err.push_str(text);
        self.err.push('\n');
    }
    fn read_line(&mut self, prompt: &str) -> Option<String> {
        self.out.push_str(prompt);
        self.lines.pop_front()
    }
    fn read_secret(&mut self, prompt: &str) -> Option<String> {
        self.out.push_str(prompt);
        self.secrets.pop_front()
    }
}

async fn authenticates(client: &reqwest::Client, base: &str, user: &str, password: &str) -> bool {
    client.get(format!("{base}/_security/_authenticate")).basic_auth(user, Some(password)).send().await
        .map(|r| r.status().is_success()).unwrap_or(false)
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn resets_the_elastic_password_through_a_temporary_file_superuser() {
    let dir = evidence::retained_dir("reset_password");
    let conf = dir.path().join("config");
    std::fs::create_dir_all(&conf).unwrap();
    std::fs::write(conf.join("users"), "").unwrap();
    std::fs::write(conf.join("users_roles"), "").unwrap();
    let mut settings = Settings::new();
    for (key, value) in [
        ("cluster.name", json!("reset-password")), ("node.name", json!("n0")),
        ("path.data", json!(dir.path().join("data").to_string_lossy())),
        ("path.logs", json!(dir.path().join("logs").to_string_lossy())),
        ("path.conf", json!(conf.to_string_lossy())),
        ("network.host", json!("127.0.0.1")), ("http.port", json!("0")),
        ("transport.port", json!("0")), ("discovery.type", json!("single-node")),
        ("xpack.security.enabled", json!("true")), ("bootstrap.password", json!("test-password")),
        ("xpack.security.authc.password_hashing.algorithm", json!("pbkdf2_1000")),
        ("cluster.routing.allocation.disk.watermark.low", json!("1b")),
        ("cluster.routing.allocation.disk.watermark.high", json!("1b")),
        ("cluster.routing.allocation.disk.watermark.flood_stage", json!("1b")),
    ] { settings.insert(key.into(), value); }
    let (node, listener) = elasticsearch_node::node::ClusterNode::start(NodeConfig::from_settings(settings).unwrap()).await.unwrap();
    let base = format!("http://127.0.0.1:{}", ports::http_port(&node));
    elasticsearch_node::rest::register(&node);
    elasticsearch_node::snapshot_api::register(&node);
    let server = tokio::spawn(async move { elasticsearch_node::front::serve(node, listener).await.unwrap(); });
    let client = reqwest::Client::builder().timeout(Duration::from_secs(10)).build().unwrap();
    let mut ready = false;
    for _ in 0..150 {
        assert!(!server.is_finished(), "node exited at startup");
        if let Ok(r) = client.get(format!("{base}/_cluster/health")).basic_auth("elastic", Some("test-password")).send().await {
            if r.status().is_success() { ready = true; break; }
        }
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    assert!(ready, "secured node did not become ready");

    let env: BTreeMap<String, String> = BTreeMap::from([("ES_PATH_CONF".to_string(), conf.to_string_lossy().into_owned())]);
    let args = |extra: &[&str]| -> Vec<String> {
        let mut a: Vec<String> = ["-u", "elastic", "--url", base.as_str(), "-E", "xpack.security.authc.password_hashing.algorithm=pbkdf2_1000"].iter().map(|s| s.to_string()).collect();
        a.extend(extra.iter().map(|s| s.to_string()));
        a
    };

    // Auto mode: confirmed at the prompt, prints the generated password.
    let mut term = Script { lines: VecDeque::from(["y".to_string()]), ..Default::default() };
    run(&parse_args(&args(&[])).unwrap(), &env, &mut term).await.unwrap_or_else(|e| panic!("{e}\nout: {}\nerr: {}", term.out, term.err));
    assert!(term.out.contains("This tool will reset the password of the [elastic] user to an autogenerated value."), "{}", term.out);
    assert!(term.out.contains("Please confirm that you would like to continue [y/N]"), "{}", term.out);
    assert!(term.out.contains("Password for the [elastic] user successfully reset.\nNew value: "), "{}", term.out);
    let generated = term.out.rsplit("New value: ").next().unwrap().trim().to_string();
    assert_eq!(generated.len(), 20);
    assert!(authenticates(&client, &base, "elastic", &generated).await);
    assert!(!authenticates(&client, &base, "elastic", "test-password").await, "the bootstrap password no longer applies");
    // The temporary superuser is gone from both files.
    assert_eq!(std::fs::read_to_string(conf.join("users")).unwrap(), "");
    assert_eq!(std::fs::read_to_string(conf.join("users_roles")).unwrap(), "");

    // Declining the prompt changes nothing (ES: "User cancelled operation", exit 0).
    let mut term = Script { lines: VecDeque::from(["n".to_string()]), ..Default::default() };
    let e = run(&parse_args(&args(&[])).unwrap(), &env, &mut term).await.unwrap_err();
    assert_eq!((e.code, e.message.as_str()), (0, "User cancelled operation"));
    assert!(authenticates(&client, &base, "elastic", &generated).await);

    // Interactive + batch: prompted twice, validated, no confirmation.
    let secrets = ["short", "abcdef1", "abcdef2", "chosen-pw", "chosen-pw"].map(String::from);
    let mut term = Script { secrets: VecDeque::from(secrets.to_vec()), ..Default::default() };
    run(&parse_args(&args(&["-i", "-b"])).unwrap(), &env, &mut term).await.unwrap_or_else(|e| panic!("{e}\nout: {}\nerr: {}", term.out, term.err));
    assert!(term.err.contains("passwords must be at least [6] characters long\nTry again.\n"), "{}", term.err);
    assert!(term.err.contains("Passwords do not match.\nTry again.\n"), "{}", term.err);
    assert!(!term.out.contains("New value"), "{}", term.out);
    assert!(authenticates(&client, &base, "elastic", "chosen-pw").await);

    // A user that does not exist: ES's TEMP_FAILURE, and the temporary user is still removed.
    let mut term = Script::default();
    let mut a = args(&["-b"]);
    a[1] = "no_such_user".into();
    let e = run(&parse_args(&a).unwrap(), &env, &mut term).await.unwrap_err();
    assert_eq!((e.code, e.message.as_str()), (75, "Failed to reset password for the [no_such_user] user"));
    assert_eq!(std::fs::read_to_string(conf.join("users")).unwrap(), "");

    // No node listening: UNAVAILABLE from the health check.
    let mut term = Script::default();
    let mut a = args(&["-b"]);
    a[3] = "http://127.0.0.1:1".into();
    let e = run(&parse_args(&a).unwrap(), &env, &mut term).await.unwrap_err();
    assert_eq!(e.code, 69, "{e}");
    assert!(e.message.starts_with("Failed to determine the health of the cluster."), "{e}");
    server.abort();
}
