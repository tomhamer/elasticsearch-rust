    const BODY: &str = "{\"index\":{\"_index\":\"a\",\"_id\":\"1\"}}\n{\"f\":1}\n{\"delete\":{\"_index\":\"b\",\"_id\":\"2\"}}\n{\"update\":{\"_id\":\"3\"}}\r\n{\"doc\":{\"f\":2}}\n\n{\"create\":{\"_index\":\"a\"}}\n{\"f\":3}\n";

