        assert_eq!(items.len(), 4);
        assert_eq!(items[0].index.as_deref(), Some("a"));
        assert_eq!(items[1].source_line, None);
        assert_eq!(items[2].index.as_deref(), Some("d"));
        assert_eq!(items[2].source_line.as_deref(), Some("{\"doc\":{\"f\":2}}"));
