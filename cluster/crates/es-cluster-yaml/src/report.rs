//! JSON + Markdown reports, with the single-node runner's JSON as baseline.

use crate::exec::{normalize, Outcome};
use crate::TestResult;
use serde_json::{json, Value};
use std::collections::{BTreeMap, HashMap};
use std::path::Path;

const NOTES_START: &str = "<!-- notes:start -->";
const NOTES_END: &str = "<!-- notes:end -->";

/// Single-node results keyed by `(file, test name)`: `(status, msg)`.
pub type Baseline = HashMap<(String, String), (String, String)>;

pub fn load_baseline(p: &Path) -> Baseline {
    let v: Value = std::fs::read(p).ok().and_then(|b| serde_json::from_slice(&b).ok()).unwrap_or(Value::Null);
    v.as_array()
        .map(|a| {
            a.iter()
                .map(|r| {
                    let s = |k: &str| r[k].as_str().unwrap_or("").to_string();
                    ((s("file"), s("name")), (s("status"), s("msg")))
                })
                .collect()
        })
        .unwrap_or_default()
}

fn status(o: &Outcome) -> &'static str {
    match o {
        Outcome::Pass => "pass",
        Outcome::Fail { .. } => "fail",
        Outcome::Skip(_) => "skip",
    }
}

pub fn write_json(path: &Path, results: &[TestResult]) {
    let v: Vec<_> = results
        .iter()
        .map(|r| {
            let (msg, cat) = match &r.outcome {
                Outcome::Pass => (String::new(), String::new()),
                Outcome::Fail { msg, category } => (msg.clone(), category.clone()),
                Outcome::Skip(s) => (s.clone(), String::new()),
            };
            json!({"file": r.file, "dir": r.dir, "name": r.name, "status": status(&r.outcome), "msg": msg, "category": cat})
        })
        .collect();
    let _ = std::fs::write(path, serde_json::to_vec_pretty(&v).unwrap_or_default());
}

fn md(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ").replace('`', "'")
}

#[derive(Default, Clone, Copy)]
struct Counts {
    pass: usize,
    fail: usize,
    skip: usize,
}

impl Counts {
    fn add(&mut self, s: &str) {
        match s {
            "pass" => self.pass += 1,
            "fail" => self.fail += 1,
            _ => self.skip += 1,
        }
    }
    fn rate(&self) -> String {
        let n = self.pass + self.fail + self.skip;
        if n == 0 { "–".into() } else { format!("{:.0}%", 100.0 * self.pass as f64 / n as f64) }
    }
}

#[allow(clippy::too_many_arguments)]
pub fn write_markdown(path: &Path, results: &[TestResult], base: &Baseline, version: &str, filters: &[String], urls: &[String], topology: &str) {
    let old_notes = std::fs::read_to_string(path).ok().and_then(|s| {
        let a = s.find(NOTES_START)?;
        let b = s.find(NOTES_END)?;
        Some(s[a..b + NOTES_END.len()].to_string())
    });
    let have_base = !base.is_empty();
    let mut total = Counts::default();
    let mut total_b = Counts::default();
    let mut per_dir: BTreeMap<&str, (Counts, Counts, usize)> = BTreeMap::new();
    let mut cluster_only: Vec<&TestResult> = Vec::new();
    let mut both: BTreeMap<String, Vec<&TestResult>> = BTreeMap::new();
    let mut fixed_in_cluster: Vec<&TestResult> = Vec::new();
    let mut skips: BTreeMap<String, usize> = BTreeMap::new();
    for r in results {
        let s = status(&r.outcome);
        let b = base.get(&(r.file.clone(), r.name.clone())).map(|(s, _)| s.as_str()).unwrap_or("skip");
        total.add(s);
        total_b.add(b);
        let d = per_dir.entry(r.dir.as_str()).or_default();
        d.0.add(s);
        d.1.add(b);
        match (&r.outcome, b) {
            (Outcome::Fail { .. }, "pass") => {
                cluster_only.push(r);
                d.2 += 1;
            }
            (Outcome::Fail { category, .. }, _) => both.entry(category.clone()).or_default().push(r),
            (Outcome::Pass, "fail") => fixed_in_cluster.push(r),
            (Outcome::Skip(why), _) => {
                let key = if why.starts_with("requires cluster feature `gte_v") { "requires newer version feature".to_string() } else { why.clone() };
                *skips.entry(key).or_default() += 1;
            }
            _ => {}
        }
    }
    let mut s = String::new();
    s.push_str("# Elasticsearch YAML REST suite — multi-node cluster compatibility\n\n");
    s.push_str(&format!(
        "Generated by `cluster/crates/es-cluster-yaml` (`cargo run -p es-cluster-yaml -- --url ... --baseline single.json --report`) \
         against Elasticsearch's own YAML REST tests (tag `{version}`, `tests/es-yaml`). Unlike `es-yaml-runner` (fresh in-process \
         single node per test), this runs against a live **external cluster**: requests round-robin over every node's HTTP address \
         (as ES's REST test client does) and the cluster is wiped between tests the way `ESRestTestCase.wipeCluster` does \
         (snapshots/repositories, data streams, indices incl. hidden, composable/component/legacy templates, ingest pipelines, \
         persistent+transient settings, voting exclusions, node-shutdown records; then wait for no initializing shards / pending tasks). \
         The executor is es-yaml-runner's own `exec.rs` (copied at build time), so assertion semantics are identical.\n\n\
         ES itself runs the whole core YAML suite against a 2-node cluster in `qa/smoke-test-multinode` (only 3 `cat.templates` tests \
         excluded), so these tests are expected to pass unchanged on a multi-node cluster.\n\n"
    ));
    s.push_str(&format!("**Cluster:** {}\n\n", urls.join(", ")));
    if !topology.trim().is_empty() {
        s.push_str("```\n");
        s.push_str(topology.trim_end());
        s.push_str("\n```\n\n");
    }
    if !filters.is_empty() {
        s.push_str(&format!("**Directories:** `{}`\n\n", filters.join("`, `")));
    }
    s.push_str("Required missing gates count as failures by default. Skipped/excluded cases have not passed. This report does not establish full ES9 parity.\n\n");
    s.push_str("## Overall\n\n| run | tests | pass | fail | skip | selected-case pass fraction |\n|---|---:|---:|---:|---:|---:|\n");
    s.push_str(&format!("| external cluster | {} | {} | {} | {} | {} |\n", results.len(), total.pass, total.fail, total.skip, total.rate()));
    if have_base {
        s.push_str(&format!("| single node (es-yaml-runner baseline) | {} | {} | {} | {} | {} |\n", results.len(), total_b.pass, total_b.fail, total_b.skip, total_b.rate()));
        s.push_str(&format!(
            "\n**Cluster-only failures** (pass on a single node, fail on the cluster): **{}**. Failures common to both (engine / HTTP layer, \
             not cluster-specific): {}. Pass on the cluster but fail single-node: {}.\n",
            cluster_only.len(),
            both.values().map(Vec::len).sum::<usize>(),
            fixed_in_cluster.len()
        ));
    }
    s.push('\n');
    if let Some(n) = old_notes {
        s.push_str("## Notes\n\n");
        s.push_str(&n);
        s.push_str("\n\n");
    } else {
        s.push_str(&format!("## Notes\n\n{NOTES_START}\n{NOTES_END}\n\n"));
    }

    s.push_str("## Per API directory\n\n| directory | cluster pass | fail | skip | rate | single-node pass | fail | skip | rate | cluster-only failures |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n");
    for (d, (c, b, co)) in &per_dir {
        s.push_str(&format!("| `{d}` | {} | {} | {} | {} | {} | {} | {} | {} | {} |\n", c.pass, c.fail, c.skip, c.rate(), b.pass, b.fail, b.skip, b.rate(), co));
    }

    if have_base {
        s.push_str("\n## Cluster-only failures\n\nPass against a single in-process node, fail against the cluster: regressions introduced by the cluster layer (or tests that genuinely depend on topology — see Notes).\n\n| test | failure |\n|---|---|\n");
        for r in &cluster_only {
            let msg = match &r.outcome {
                Outcome::Fail { msg, .. } => msg.chars().take(300).collect::<String>(),
                _ => String::new(),
            };
            s.push_str(&format!("| `{}` :: {} | {} |\n", md(&r.file), md(&r.name), md(&msg)));
        }
        if !fixed_in_cluster.is_empty() {
            s.push_str("\n## Pass on the cluster, fail single-node\n\n");
            for r in &fixed_in_cluster {
                s.push_str(&format!("- `{}` :: {}\n", md(&r.file), md(&r.name)));
            }
        }
    }

    s.push_str("\n## Failures shared with the single-node run (by cause)\n\n| count | cause | examples |\n|---:|---|---|\n");
    let mut cs: Vec<_> = both.iter().collect();
    cs.sort_by(|a, b| b.1.len().cmp(&a.1.len()).then(a.0.cmp(b.0)));
    for (cat, rs) in cs.iter().take(80) {
        let ex: Vec<String> = rs.iter().take(3).map(|r| format!("`{}` :: {}", md(&r.file), md(&r.name))).collect();
        s.push_str(&format!("| {} | `{}` | {} |\n", rs.len(), md(&normalize(cat)), ex.join("<br>")));
    }

    s.push_str("\n## Skip reasons\n\n| reason | tests |\n|---|---:|\n");
    let mut sk: Vec<_> = skips.into_iter().collect();
    sk.sort_by(|a, b| b.1.cmp(&a.1));
    for (why, n) in sk.iter().take(40) {
        s.push_str(&format!("| {} | {n} |\n", md(why)));
    }
    if let Some(dir) = path.parent() {
        let _ = std::fs::create_dir_all(dir);
    }
    let _ = std::fs::write(path, s);
}
