#!/usr/bin/env python3
"""Translate a Snowball-generated Lucene Java stemmer (org.tartarus.snowball.ext)
into Rust over `super::snowball::{Among, Env}`. Handles the subset the
generator emits: Among tables, groupings, int/boolean fields, boolean
methods, labeled blocks / loops, switch on among_var, cursor arithmetic."""
import re, sys

src = open(sys.argv[1]).read()
name = sys.argv[2]  # e.g. Irish
doc = sys.argv[3] if len(sys.argv) > 3 else ''

def jstr_to_chars(s):
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == '\\':
            n = s[i + 1]
            if n == 'u':
                out.append(chr(int(s[i + 2:i + 6], 16))); i += 6; continue
            out.append({'n': '\n', 't': '\t', '\\': '\\', '"': '"', "'": "'"}[n]); i += 2; continue
        out.append(c); i += 1
    return out

def rchar(c):
    if c == "'": return "'\\''"
    if c == '\\': return "'\\\\'"
    if ord(c) < 128 and c.isprintable(): return "'%s'" % c
    return "'\\u{%x}'" % ord(c)

def rstr(chars):
    out = ''
    for c in chars:
        if c == '"': out += '\\"'
        elif c == '\\': out += '\\\\'
        elif ord(c) < 128 and c.isprintable(): out += c
        else: out += '\\u{%x}' % ord(c)
    return '"' + out + '"'

out = []
out.append('// Translated from Lucene 10.3.2 `org.tartarus.snowball.ext.%sStemmer`' % name)
out.append('// (generated by Snowball 2.2.0) by tools/snowball2rs.py; do not edit by hand.')
if doc:
    out.append('//! ' + doc)
out.append('#![allow(unused, non_snake_case, unused_parens, unused_labels, clippy::all)]')
out.append('use super::snowball::{Among, Env};')
out.append('')

for m in re.finditer(r'private static final Among (a_\d+)\[\] = \{(.*?)\};', src, re.S):
    nm, body = m.group(1), m.group(2)
    rows = re.findall(r'new Among\("((?:[^"\\]|\\.)*)", (-?\d+), (-?\d+)\)', body)
    out.append('static %s: &[Among] = &[' % nm.upper())
    for s, sub, res in rows:
        chars = jstr_to_chars(s)
        out.append('    Among { s: &[%s], substring_i: %s, result: %s },' % (', '.join(rchar(c) for c in chars), sub, res))
    out.append('];')
for m in re.finditer(r'private static final char (g_\w+)\[\] = \{(.*?)\};', src, re.S):
    vals = [v.strip() for v in m.group(2).split(',') if v.strip()]
    out.append('static %s: &[u8] = &[%s];' % (m.group(1).upper(), ', '.join(vals)))

fields = re.findall(r'private (int|boolean) ([IB]_\w+);', src)
out.append('')
out.append('pub struct %sStemmer {' % name)
out.append('    e: Env,')
for t, f in fields:
    out.append('    %s: %s,' % (f, 'i32' if t == 'int' else 'bool'))
out.append('}')
out.append('')
out.append('impl %sStemmer {' % name)
out.append('    fn new(word: &str) -> Self {')
out.append('        %sStemmer { e: Env::new(word)%s }' % (name, ''.join(', %s: %s' % (f, '0' if t == 'int' else 'false') for t, f in fields)))
out.append('    }')

CALLS = r'\b(in_grouping|in_grouping_b|out_grouping|out_grouping_b|find_among|find_among_b|slice_del|slice_from|eq_s|eq_s_b|insert|slice_check)\('

def expr(s):
    # string literals first (protect)
    lits = []
    def lit(m):
        lits.append(rstr(jstr_to_chars(m.group(1))))
        return '\x00%d\x00' % (len(lits) - 1)
    s = re.sub(r'"((?:[^"\\]|\\.)*)"', lit, s)
    s = re.sub(r'\bcursor\+\+', 'cursor += 1', s)
    s = re.sub(r'\bcursor--', 'cursor -= 1', s)
    s = re.sub(r'\b(cursor|limit_backward|limit|bra|ket)\b', r'self.e.\1', s)
    s = re.sub(r'(?<![\w.])length\b', 'self.e.length()', s)
    s = re.sub(r'(?<![\w.])([IB]_\w+)\b', r'self.\1', s)
    s = re.sub(CALLS, r'self.e.\1(', s)
    s = re.sub(r'(?<![\w.])(r_\w+)\(', r'self.\1(', s)
    s = re.sub(r'\b(a_\d+|g_\w+)\b', lambda m: m.group(1).upper(), s)
    s = re.sub(r'\x00(\d+)\x00', lambda m: lits[int(m.group(1))], s)
    return s

methods = re.finditer(r'\n  (?:private|public) boolean (\w+)\(\) \{\n(.*?)\n  \}\n', src, re.S)
loopn = [0]
for m in methods:
    mname, body = m.group(1), m.group(2)
    if mname == 'equals':
        continue
    vis = 'pub ' if mname == 'stem' else ''
    out.append('    %sfn %s(&mut self) -> bool {' % (vis, mname))
    stack = []  # entries: ['block'|'loop'|'switch'|'if', label, arm_open]
    pending = None
    for raw in body.split('\n'):
        line = raw.strip()
        ind = '        ' + '    ' * len(stack)
        if not line:
            continue
        m2 = re.match(r'^(\w+):$', line)
        if m2:
            pending = m2.group(1); continue
        if line == '{':
            lab = pending or ('blk%d' % loopn[0]); loopn[0] += 1; pending = None
            out.append(ind + "'%s: {" % lab); stack.append(['block', lab, False]); continue
        if line == 'while (true) {':
            lab = pending or ('loop%d' % loopn[0]); loopn[0] += 1; pending = None
            out.append(ind + "'%s: loop {" % lab); stack.append(['loop', lab, False]); continue
        m2 = re.match(r'^switch \((\w+)\) \{$', line)
        if m2:
            out.append(ind + 'match %s {' % m2.group(1)); stack.append(['switch', None, False]); continue
        m2 = re.match(r'^case (-?\d+):$', line)
        if m2:
            top = stack[-1]; assert top[0] == 'switch'
            if top[2]:
                out.append(ind[:-4] + '    }')
            out.append(ind + '%s => {' % m2.group(1)); top[2] = True; continue
        if line == 'break;':
            # innermost of switch-arm / loop
            for e in reversed(stack):
                if e[0] == 'switch':
                    break
                if e[0] == 'loop':
                    out.append(ind + "break '%s;" % e[1]); break
            continue
        if line == 'continue;':
            for e in reversed(stack):
                if e[0] == 'loop':
                    out.append(ind + "continue '%s;" % e[1]); break
            continue
        m2 = re.match(r'^(break|continue) (\w+);$', line)
        if m2:
            out.append(ind + "%s '%s;" % (m2.group(1), m2.group(2))); continue
        if line == '}':
            top = stack.pop()
            ind = '        ' + '    ' * len(stack)
            if top[0] == 'switch':
                if top[2]:
                    out.append(ind + '        }')
                out.append(ind + '    _ => {}')
            out.append(ind + '}'); continue
        m2 = re.match(r'^if \((.*)\) \{$', line)
        if m2:
            out.append(ind + 'if %s {' % expr(m2.group(1))); stack.append(['if', None, False]); continue
        if line == '} else {':
            out.append(ind[:-4] + '} else {'); continue
        m2 = re.match(r'^(int|boolean) (\w+);$', line)
        if m2:
            out.append(ind + 'let mut %s: %s = %s;' % (m2.group(2), 'i32' if m2.group(1) == 'int' else 'bool', '0' if m2.group(1) == 'int' else 'false')); continue
        m2 = re.match(r'^(int|boolean) (\w+) = (.*);$', line)
        if m2:
            out.append(ind + 'let mut %s: %s = %s;' % (m2.group(2), 'i32' if m2.group(1) == 'int' else 'bool', expr(m2.group(3)))); continue
        if line.endswith(';'):
            out.append(ind + expr(line)); continue
        raise SystemExit('untranslated line in %s: %r' % (mname, line))
    assert not stack, (mname, stack)
    out.append('    }')
out.append('}')
out.append('')
out.append('/// Stem one (lowercased) word.')
out.append('pub fn stem(word: &str) -> String {')
out.append('    let mut s = %sStemmer::new(word);' % name)
out.append('    s.stem();')
out.append('    s.e.current()')
out.append('}')
print('\n'.join(out))
